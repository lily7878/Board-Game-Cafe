-- PDF rule manuals (one active per game). The AI Service indexes them; Core keeps the file and the state.
-- A replacement stays inactive while PROCESSING, so customers keep the previous manual until the new one is READY.
CREATE TABLE game_rule_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES games(id),
    file_name VARCHAR(255) NOT NULL,
    size_bytes BIGINT NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    sha256 CHAR(64) NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    status VARCHAR(16) NOT NULL,
    failure_reason VARCHAR(500),
    page_count INTEGER,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    uploaded_by_id BIGINT NOT NULL REFERENCES staff_users(id),
    uploaded_at TIMESTAMPTZ NOT NULL,
    processed_at TIMESTAMPTZ,
    removed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_rule_doc_size CHECK (size_bytes > 0),
    CONSTRAINT chk_rule_doc_status CHECK (status IN ('PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT chk_rule_doc_active_ready CHECK (NOT active OR (status = 'READY' AND removed_at IS NULL)),
    CONSTRAINT chk_rule_doc_pages CHECK (page_count IS NULL OR page_count > 0)
);
CREATE UNIQUE INDEX uq_rule_doc_active_per_game ON game_rule_documents (game_id) WHERE active;
CREATE INDEX idx_rule_docs_game ON game_rule_documents (game_id, uploaded_at DESC);
CREATE INDEX idx_rule_docs_processing ON game_rule_documents (status) WHERE status = 'PROCESSING';
