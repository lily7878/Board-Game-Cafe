CREATE TABLE table_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES cafe_tables(id),
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    join_token_digest VARCHAR(64) NOT NULL UNIQUE,
    pin_hash VARCHAR(100) NOT NULL,
    failed_join_attempts INTEGER NOT NULL DEFAULT 0,
    join_locked_until TIMESTAMPTZ,
    started_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    CONSTRAINT chk_table_session_status CHECK (status IN ('ACTIVE', 'CHECKOUT_PENDING', 'CLOSED'))
);
CREATE UNIQUE INDEX uq_open_session_per_table ON table_sessions(table_id) WHERE status <> 'CLOSED';

CREATE TABLE session_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id),
    display_name VARCHAR(80) NOT NULL,
    access_token_hash VARCHAR(64) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    joined_at TIMESTAMPTZ NOT NULL,
    left_at TIMESTAMPTZ,
    CONSTRAINT uq_participant_session UNIQUE (id, session_id)
);
CREATE INDEX idx_participants_session ON session_participants(session_id);

CREATE TABLE game_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id),
    participant_id BIGINT NOT NULL,
    game_id BIGINT NOT NULL REFERENCES games(id),
    game_copy_id BIGINT,
    status VARCHAR(16) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    reserved_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    returned_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    resolution_reason TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_request_participant_session FOREIGN KEY (participant_id, session_id)
        REFERENCES session_participants(id, session_id),
    CONSTRAINT chk_game_request_status CHECK (status IN
        ('REQUESTED', 'RESERVED', 'DELIVERED', 'RETURNED', 'REJECTED', 'CANCELLED'))
);
ALTER TABLE game_copies ADD CONSTRAINT uq_game_copy_id_game UNIQUE (id, game_id);
ALTER TABLE game_requests ADD CONSTRAINT fk_request_copy_game
    FOREIGN KEY (game_copy_id, game_id) REFERENCES game_copies(id, game_id);
CREATE UNIQUE INDEX uq_active_request_per_copy ON game_requests(game_copy_id)
    WHERE status IN ('RESERVED', 'DELIVERED');
CREATE INDEX idx_requests_session_status ON game_requests(session_id, status);
CREATE INDEX idx_requests_game_status ON game_requests(game_id, status);
