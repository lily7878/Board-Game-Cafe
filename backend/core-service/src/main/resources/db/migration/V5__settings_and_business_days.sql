-- Simulated business days: sequential, at most one OPEN, the next one opened atomically by End of Day.
CREATE TABLE business_days (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_number INTEGER NOT NULL UNIQUE,
    label VARCHAR(50) NOT NULL,
    status VARCHAR(16) NOT NULL,
    opened_at TIMESTAMPTZ NOT NULL,
    finalized_at TIMESTAMPTZ,
    finalized_by_id BIGINT REFERENCES staff_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_business_day_number CHECK (day_number > 0),
    CONSTRAINT chk_business_day_status CHECK (status IN ('OPEN', 'FINALIZED')),
    CONSTRAINT chk_business_day_finalized CHECK (
        (status = 'OPEN' AND finalized_at IS NULL) OR (status = 'FINALIZED' AND finalized_at IS NOT NULL))
);
CREATE UNIQUE INDEX uq_single_open_business_day ON business_days ((status)) WHERE status = 'OPEN';
