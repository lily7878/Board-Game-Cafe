-- Informative opening hours (1 = Monday ... 7 = Sunday); never used to restrict sessions or End of Day.
CREATE TABLE opening_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week INTEGER NOT NULL UNIQUE,
    open_time TIME,
    close_time TIME,
    closed BOOLEAN NOT NULL,
    CONSTRAINT chk_opening_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_opening_hours_times CHECK (
        (closed AND open_time IS NULL AND close_time IS NULL)
        OR (NOT closed AND open_time IS NOT NULL AND close_time IS NOT NULL AND open_time < close_time))
);
INSERT INTO opening_hours (day_of_week, open_time, close_time, closed)
