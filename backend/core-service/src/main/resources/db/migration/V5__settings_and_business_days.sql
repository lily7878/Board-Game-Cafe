-- Global cafe configuration: exactly one row, created here so the system is usable without manual inserts.
CREATE TABLE cafe_settings (
    id BIGINT PRIMARY KEY,
    cafe_name VARCHAR(100) NOT NULL,
    access_fee_price NUMERIC(10, 2) NOT NULL,
    max_delivered_games_per_table INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_cafe_settings_single_row CHECK (id = 1),
    CONSTRAINT chk_cafe_settings_fee CHECK (access_fee_price >= 0),
    CONSTRAINT chk_cafe_settings_max_games CHECK (max_delivered_games_per_table > 0)
);
