-- Final snapshot of a simulated business day, written once by End of Day and never modified afterwards.
-- It is intentionally denormalized: later catalog or menu edits must not change historical reports.
CREATE TABLE daily_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_day_id BIGINT NOT NULL UNIQUE REFERENCES business_days(id),
    total_revenue NUMERIC(12, 2) NOT NULL,
    menu_revenue NUMERIC(12, 2) NOT NULL,
    access_fee_revenue NUMERIC(12, 2) NOT NULL,
    closed_sessions_count INTEGER NOT NULL,
    delivered_orders_count INTEGER NOT NULL,
    products_sold_count INTEGER NOT NULL,
    games_delivered_count INTEGER NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_daily_report_amounts CHECK (
        total_revenue >= 0 AND menu_revenue >= 0 AND access_fee_revenue >= 0),
    CONSTRAINT chk_daily_report_counts CHECK (
        closed_sessions_count >= 0 AND delivered_orders_count >= 0
        AND products_sold_count >= 0 AND games_delivered_count >= 0)
);

CREATE TABLE daily_product_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES daily_reports(id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id),
    product_name_snapshot VARCHAR(150) NOT NULL,
    quantity_sold INTEGER NOT NULL,
    revenue NUMERIC(12, 2) NOT NULL,
    CONSTRAINT uq_daily_product_stat UNIQUE (report_id, menu_item_id),
    CONSTRAINT chk_daily_product_stat CHECK (quantity_sold >= 0 AND revenue >= 0)
);

CREATE TABLE daily_game_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES daily_reports(id),
    game_id BIGINT NOT NULL REFERENCES games(id),
    game_title_snapshot VARCHAR(150) NOT NULL,
    times_requested INTEGER NOT NULL,
    times_delivered INTEGER NOT NULL,
    CONSTRAINT uq_daily_game_stat UNIQUE (report_id, game_id),
    CONSTRAINT chk_daily_game_stat CHECK (times_requested >= 0 AND times_delivered >= 0)
);

CREATE INDEX idx_daily_game_stats_game ON daily_game_stats (game_id);
CREATE INDEX idx_daily_product_stats_item ON daily_product_stats (menu_item_id);
