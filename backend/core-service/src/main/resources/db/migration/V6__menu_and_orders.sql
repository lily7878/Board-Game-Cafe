-- Menu: each product belongs to exactly one category (1:N), unlike games (N:M).
CREATE TABLE menu_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL
);
CREATE UNIQUE INDEX uq_menu_category_name_lower ON menu_categories (lower(name));

CREATE TABLE menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES menu_categories(id),
    name VARCHAR(150) NOT NULL,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL,
    available BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_menu_item_price CHECK (price >= 0)
);
CREATE INDEX idx_menu_items_category ON menu_items (category_id);

-- Orders: one participant, one session; the participant must belong to that session (composite FK).
CREATE TABLE food_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id),
    participant_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    cancellation_reason VARCHAR(24),
    processed_by_id BIGINT REFERENCES staff_users(id),
    placed_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ,
    ready_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_participant_session FOREIGN KEY (participant_id, session_id)
        REFERENCES session_participants(id, session_id),
    CONSTRAINT chk_food_order_status CHECK (status IN
        ('PLACED', 'ACCEPTED', 'PREPARING', 'READY', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT chk_food_order_cancellation CHECK (
        (status = 'CANCELLED' AND cancellation_reason IN ('CUSTOMER_CANCELLED', 'ALL_ITEMS_REJECTED'))
        OR (status <> 'CANCELLED' AND cancellation_reason IS NULL))
);
CREATE INDEX idx_food_orders_session_status ON food_orders (session_id, status);
CREATE INDEX idx_food_orders_participant ON food_orders (participant_id);
CREATE INDEX idx_food_orders_status_placed ON food_orders (status, placed_at);

-- Order lines keep the product name and unit price at the moment of ordering (snapshot).
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES food_orders(id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id),
    product_name_snapshot VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    status VARCHAR(16) NOT NULL,
    rejection_reason TEXT,
    CONSTRAINT chk_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_item_price CHECK (unit_price >= 0),
    CONSTRAINT chk_order_item_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT chk_order_item_rejection CHECK (status = 'REJECTED' OR rejection_reason IS NULL)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_menu_item ON order_items (menu_item_id);
