-- Number of physically present people billed for a session (0..1 row per session).
-- The unit price is not repeated here: table_sessions.access_fee_unit_price is the fixed snapshot.
CREATE TABLE session_fees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE REFERENCES table_sessions(id),
    quantity INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    updated_by_participant_id BIGINT REFERENCES session_participants(id),
    updated_by_staff_id BIGINT REFERENCES staff_users(id),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_session_fee_quantity CHECK (quantity >= 1),
    CONSTRAINT chk_session_fee_single_author
        CHECK (num_nonnulls(updated_by_participant_id, updated_by_staff_id) = 1)
);

-- Attempts to pay the whole bill (simulated). The initiator must belong to the paid session.
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_sessions(id),
    initiated_by_id BIGINT NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    status VARCHAR(16) NOT NULL,
    method VARCHAR(16) NOT NULL,
    idempotency_key UUID NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    failure_reason TEXT,
    CONSTRAINT fk_payment_participant_session FOREIGN KEY (initiated_by_id, session_id)
        REFERENCES session_participants(id, session_id),
    CONSTRAINT chk_payment_amount CHECK (amount >= 0),
    CONSTRAINT chk_payment_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT chk_payment_method CHECK (method IN ('SIMULATED')),
    CONSTRAINT chk_payment_completion CHECK (status = 'PENDING' OR completed_at IS NOT NULL),
    CONSTRAINT chk_payment_failure CHECK (status = 'FAILED' OR failure_reason IS NULL)
);
-- Last line of defence: at most one successful payment per session, even under concurrency.
CREATE UNIQUE INDEX uq_succeeded_payment_per_session ON payments (session_id) WHERE status = 'SUCCEEDED';
CREATE INDEX idx_payments_session ON payments (session_id);
