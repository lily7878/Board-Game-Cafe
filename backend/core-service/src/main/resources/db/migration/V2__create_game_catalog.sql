CREATE TABLE game_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    active BOOLEAN NOT NULL
);

CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    short_rules TEXT,
    min_players INTEGER NOT NULL,
    max_players INTEGER NOT NULL,
    duration_minutes INTEGER NOT NULL,
    minimum_age INTEGER NOT NULL,
    difficulty VARCHAR(16) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT chk_games_min_players CHECK (min_players >= 1),
    CONSTRAINT chk_games_max_players CHECK (max_players >= min_players),
    CONSTRAINT chk_games_duration_minutes CHECK (duration_minutes > 0),
    CONSTRAINT chk_games_minimum_age CHECK (minimum_age >= 0),
    CONSTRAINT chk_games_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE TABLE game_category_links (
    game_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    CONSTRAINT pk_game_category_links PRIMARY KEY (game_id, category_id),
    CONSTRAINT fk_game_category_links_game 
        FOREIGN KEY (game_id) REFERENCES games(id),
    CONSTRAINT fk_game_category_links_category 
        FOREIGN KEY (category_id) REFERENCES game_categories(id)
);

CREATE TABLE game_copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    inventory_code VARCHAR(255) NOT NULL UNIQUE,
    condition_status VARCHAR(32) NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_game_copies_game
        FOREIGN KEY (game_id) REFERENCES games(id),

    CONSTRAINT chk_game_copies_condition_status
        CHECK (
            condition_status IN (
                'USABLE',
                'UNDER_MAINTENANCE',
                'UNAVAILABLE'
            )
        )
);

CREATE INDEX idx_game_category_links_category_id
    ON game_category_links (category_id);

CREATE INDEX idx_game_copies_game_id
    ON game_copies (game_id);